import CoreGraphics
import Foundation
import ImageIO
import UniformTypeIdentifiers

enum SecurityMode: String, CaseIterable, Identifiable, Codable {
    case normal
    case sensitive

    var id: String { rawValue }
}

enum ClipboardFilter {
    static let sourceType = "org.nspasteboard.source"

    static let imageTypesInPreferenceOrder = [UTType.png.identifier, UTType.jpeg.identifier, UTType.tiff.identifier]
    static let maximumImageBytes = 16_000_000

    private static let maximumSourceEdge = 8_192
    private static let maximumSourcePixels = 16_000_000
    private static let maximumOutputEdge = 3_072
    private static let plainTextType = "public.utf8-plain-text"
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "public.file-url",
        "NSFilenamesPboardType",
        "com.apple.pasteboard.promised-file-url",
        "NSFilesPromisePboardType",
    ]
    // Registered conformance checks can miss even standard image identifiers.
    private static let imageTypes = Set(CGImageSourceCopyTypeIdentifiers() as? [String] ?? [])
        .union(["public.image", "public.svg-image"])
    private static let ignoredApps: Set<String> = [
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.apple.keychainaccess",
        "com.apple.passwords",
        "com.bitwarden.desktop",
        "org.keepassxc.keepassxc",
    ]

    private static let secretPattern = try! NSRegularExpression(pattern: [
        #"-----BEGIN (?:[A-Z0-9]+ )*PRIVATE KEY(?: BLOCK)?-----"#,
        #"(?<![A-Za-z0-9_])(?:AKIA|ASIA)[A-Z0-9]{16}(?![A-Za-z0-9_])"#,
        #"(?<![A-Za-z0-9_])gh[pousr]_[A-Za-z0-9]{36,}(?![A-Za-z0-9_])"#,
        #"(?<![A-Za-z0-9_])github_pat_[A-Za-z0-9_]{40,}(?![A-Za-z0-9_])"#,
        #"(?<![A-Za-z0-9_])(?:xox[baprs]-|xapp-)[A-Za-z0-9-]{16,}(?![A-Za-z0-9_-])"#,
        #"(?<![A-Za-z0-9_])AIza[A-Za-z0-9_-]{35}(?![A-Za-z0-9_-])"#,
        #"(?<![A-Za-z0-9_])(?:sk|rk)_(?:live|test)_[A-Za-z0-9]{16,}(?![A-Za-z0-9_])"#,
        #"(?<![A-Za-z0-9_])sk-(?:(?:proj|svcacct|admin|ant)-[A-Za-z0-9_-]{20,}|[A-Za-z0-9]{32,})(?![A-Za-z0-9_-])"#,
        #"(?<![A-Za-z0-9_])glpat-[A-Za-z0-9_-]{20,}(?![A-Za-z0-9_-])"#,
        #"(?<![A-Za-z0-9_])npm_[A-Za-z0-9]{36,}(?![A-Za-z0-9_])"#,
        #"(?<![A-Za-z0-9_])pypi-[A-Za-z0-9_-]{32,}(?![A-Za-z0-9_-])"#,
        #"(?<![A-Za-z0-9_])eyJ[A-Za-z0-9_-]{5,}\.eyJ[A-Za-z0-9_-]{5,}\.[A-Za-z0-9_-]{8,}(?![A-Za-z0-9_-])"#,
    ].joined(separator: "|"))
    private static let fileURLPattern = try! NSRegularExpression(pattern: #"(?i)\bfile:/"#)

    static func shouldRecord(
        types: Set<String>,
        sourceBundleID: String?,
        securityMode: SecurityMode = .sensitive
    ) -> Bool {
        if securityMode == .sensitive {
            guard types.isDisjoint(with: ignoredTypes),
                  !isIgnoredApp(sourceBundleID),
                  !types.contains(where: { UTType($0)?.conforms(to: .fileURL) == true }) else { return false }
        }

        return !types.isDisjoint(with: imageTypesInPreferenceOrder) || allowsTextFallback(types: types)
    }

    static func allowsTextFallback(types: Set<String>) -> Bool {
        let otherTypes = types.subtracting(imageTypesInPreferenceOrder)
        guard otherTypes.contains(plainTextType),
              otherTypes.isDisjoint(with: imageTypes) else { return false }

        return !otherTypes.contains { UTType($0)?.conforms(to: .image) == true }
    }

    static func isIgnoredApp(_ bundleID: String?) -> Bool {
        guard let bundleID else { return false }
        return ignoredApps.contains(bundleID.trimmingCharacters(in: .whitespacesAndNewlines).lowercased())
    }

    static func isSensitive(_ text: String) -> Bool {
        secretPattern.firstMatch(in: text, range: NSRange(text.startIndex..., in: text)) != nil
    }

    static func containsFileURL(_ text: String) -> Bool {
        fileURLPattern.firstMatch(in: text, range: NSRange(text.startIndex..., in: text)) != nil
    }

    static func normalizedPNG(from data: Data, advertisedType: String) -> Data? {
        guard data.count <= maximumImageBytes, matchesSignature(data, type: advertisedType) else { return nil }

        let sourceOptions = [kCGImageSourceShouldCache: false] as CFDictionary
        guard let source = CGImageSourceCreateWithData(data as CFData, sourceOptions),
              CGImageSourceGetType(source) as String? == advertisedType,
              CGImageSourceGetStatus(source) == .statusComplete,
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = properties[kCGImagePropertyPixelWidth] as? Int,
              let height = properties[kCGImagePropertyPixelHeight] as? Int,
              (1...maximumSourceEdge).contains(width), (1...maximumSourceEdge).contains(height),
              width * height <= maximumSourcePixels else { return nil }

        let thumbnailOptions = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceShouldCacheImmediately: true,
            kCGImageSourceThumbnailMaxPixelSize: maximumOutputEdge,
        ] as CFDictionary
        guard let image = CGImageSourceCreateThumbnailAtIndex(source, 0, thumbnailOptions),
              CGImageSourceGetStatusAtIndex(source, 0) == .statusComplete,
              (1...maximumOutputEdge).contains(image.width), (1...maximumOutputEdge).contains(image.height),
              let colorSpace = CGColorSpace(name: CGColorSpace.sRGB),
              let bitmap = CGContext(data: nil, width: image.width, height: image.height, bitsPerComponent: 8,
                                     bytesPerRow: 0, space: colorSpace,
                                     bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue) else { return nil }

        // Redrawing one frame bakes in orientation and keeps source metadata out of history.
        bitmap.draw(image, in: CGRect(x: 0, y: 0, width: image.width, height: image.height))
        let output = NSMutableData()
        guard let pixels = bitmap.makeImage(),
              let destination = CGImageDestinationCreateWithData(output, UTType.png.identifier as CFString, 1, nil)
        else { return nil }
        CGImageDestinationAddImage(destination, pixels, nil)
        guard CGImageDestinationFinalize(destination), output.length <= maximumImageBytes else { return nil }
        return output as Data
    }

    private static func matchesSignature(_ data: Data, type: String) -> Bool {
        switch type {
        case UTType.png.identifier:
            return data.starts(with: [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A])
        case UTType.jpeg.identifier:
            return data.starts(with: [0xFF, 0xD8, 0xFF])
        case UTType.tiff.identifier:
            return data.starts(with: [0x49, 0x49, 0x2A, 0x00]) || data.starts(with: [0x4D, 0x4D, 0x00, 0x2A])
        default:
            return false
        }
    }
}
